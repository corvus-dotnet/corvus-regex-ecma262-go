#!/usr/bin/env python3
"""Writes strings<major>_gen.go, the properties of strings of one version of Unicode for the engine (which only the v
flag can name), from strings<major>.rs of the corvus-regex-ecma262 Rust crate, so every engine holds the same Unicode
emoji sequences. The engine carries Unicode 13, 17 and 18, one file for each.

    python3 tools/unicode/gen_strings.py <path to strings<major>.rs> [output] [--check]

With --check, the output is compared with the file in place and nothing is written: the exit status is 1 when they
differ.
"""
import os
import re
import sys


def find(pattern, text, what):
    m = re.search(pattern, text, re.S)
    if m is None:
        raise SystemExit(f"the crate's properties of strings have no {what}: the generator needs updating for the crate's file")
    return m


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv
    rs = open(args[0], encoding="utf-8").read()
    version = find(r'pub\(crate\) const VERSION: &str = "([^"]+)";', rs, "VERSION").group(1)
    major = version.split(".")[0]
    output = args[1] if len(args) > 1 else f"strings{major}_gen.go"
    source = os.path.basename(args[0])
    body = find(r"pub\(crate\) static PROPERTIES: \[\(&str, &str, &str\); \d+\] = \[(.*?)\n\];", rs, "PROPERTIES").group(1)
    rows = re.findall(r'\("([^"]*)", "([^"]*)", "([^"]*)"\),', body)
    if not rows:
        raise SystemExit(f"{source} has no rows in PROPERTIES")
    parts = [
        f"// Code generated by tools/unicode/gen_strings.py from {source} of the corvus-regex-ecma262 Rust crate",
        f"// (emoji-sequences.txt and emoji-zwj-sequences.txt of Unicode {version}). DO NOT EDIT.",
        "",
        "package ecmaregex",
        "",
        f"// stringProperties{major} are each property of strings of Unicode {version} but RGI_Emoji (the union of them all):",
        "// its name, its single code points as hexadecimal ranges, and its sequences as hexadecimal code points, a space",
        "// between the code points of a sequence and a semicolon between sequences.",
        f"var stringProperties{major} = [6][3]string{{",
    ]
    for name, points, sequences in rows:
        parts.append(f'\t{{"{name}", "{points}", "{sequences}"}},')
    parts.append("}")
    text = "\n".join(parts) + "\n"
    if check:
        current = open(output, encoding="utf-8").read() if os.path.exists(output) else ""
        if current != text:
            print(f"{output} is not what {args[0]} generates; run tools/unicode/gen_strings.py", file=sys.stderr)
            sys.exit(1)
        print(f"{output} is current ({len(rows)} properties)")
        return
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {output}: {len(rows)} properties of strings, Unicode {version}")


if __name__ == "__main__":
    main()
