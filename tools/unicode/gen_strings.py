#!/usr/bin/env python3
"""Writes strings_gen.go, the properties of strings of the engine (which only the v flag can name), from
strings_gen.rs of the corvus-regex-ecma262 Rust crate, so every engine holds the same Unicode emoji sequences.

    python3 tools/unicode/gen_strings.py <path to strings_gen.rs> [output] [--check]

With --check, the output is compared with the file in place and nothing is written: the exit status is 1 when they
differ.
"""
import os
import re
import sys

OUT = "strings_gen.go"


def find(pattern, text, what):
    m = re.search(pattern, text, re.S)
    if m is None:
        raise SystemExit(f"strings_gen.rs has no {what}: the generator needs updating for the crate's file")
    return m


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv
    rs = open(args[0], encoding="utf-8").read()
    output = args[1] if len(args) > 1 else OUT
    version = find(r'pub\(crate\) const VERSION: &str = "([^"]+)";', rs, "VERSION").group(1)
    body = find(r"pub\(crate\) static PROPERTIES: \[\(&str, &str, &str\); \d+\] = \[(.*?)\n\];", rs, "PROPERTIES").group(1)
    rows = re.findall(r'\("([^"]*)", "([^"]*)", "([^"]*)"\),', body)
    if not rows:
        raise SystemExit("strings_gen.rs has no rows in PROPERTIES")
    parts = [
        "// Code generated by tools/unicode/gen_strings.py from strings_gen.rs of the corvus-regex-ecma262 Rust crate",
        f"// (emoji-sequences.txt and emoji-zwj-sequences.txt of Unicode {version}). DO NOT EDIT.",
        "",
        "package ecmaregex",
        "",
        "// stringsVersion is the version of Unicode the properties of strings are from.",
        f'const stringsVersion = "{version}"',
        "",
        "// stringProperties are each property of strings but RGI_Emoji (the union of them all): its name, its single code",
        "// points as hexadecimal ranges, and its sequences as hexadecimal code points, a space between the code points of a",
        "// sequence and a semicolon between sequences.",
        "var stringProperties = [...][3]string{",
    ]
    for name, points, sequences in rows:
        parts.append(f'\t{{"{name}", "{points}", "{sequences}"}},')
    parts.append("}")
    text = "\n".join(parts) + "\n"
    if check:
        current = open(output, encoding="utf-8").read() if os.path.exists(output) else ""
        if current != text:
            print(f"{output} is not what {args[0]} generates; run tools/unicode/gen_strings.py", file=sys.stderr)
            sys.exit(1)
        print(f"{output} is current ({len(rows)} properties)")
        return
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {output}: {len(rows)} properties of strings, Unicode {version}")


if __name__ == "__main__":
    main()
