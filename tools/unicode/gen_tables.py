#!/usr/bin/env python3
"""Writes internal/ucd/tables<major>_gen.go, the Unicode property tables of one version of Unicode for the engine,
from tables<major>.rs of the corvus-regex-ecma262 Rust crate, which holds the same data as every other engine. The
engine carries Unicode 13, 17 and 18, one file for each.

Each table is a sorted list of inclusive ranges, the code points up to U+FFFF as 16-bit bounds and the rest as 32-bit
bounds (see ucd.go). The case mappings are rows of a first code point, a delta, a length and a mask. Every name in the
file ends in the major number of the version, and data<major> gathers its lookups for ucd.go.

    python3 tools/unicode/gen_tables.py <path to tables<major>.rs> [output] [--check]

With --check, the output is compared with the file in place and nothing is written: the exit status is 1 when they
differ, so CI can tell that the tables are the crate's.
"""
import os
import re
import sys

PER_LINE = 12


def go_name(rust_name, major):
    """GC_LU -> gcLu13, SCX_CAUCASIAN_ALBANIAN -> scxCaucasianAlbanian13."""
    parts = rust_name.lower().split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:]) + major


def find(pattern, text, what):
    """The first group of a pattern that must match, or a clear failure when the crate's file has changed shape."""
    m = re.search(pattern, text, re.S)
    if m is None:
        raise SystemExit(f"the crate's tables have no {what}: the generator needs updating for the crate's file")
    return m.group(1)


def ints(text):
    return [int(x, 0) for x in re.findall(r"-?0x[0-9A-Fa-f]+|-?\d+", text)]


def numbers(values, indent):
    """Hex literals, PER_LINE to a line, each line indented."""
    lines = []
    for i in range(0, len(values), PER_LINE):
        lines.append(indent + ", ".join("0x%X" % v for v in values[i:i + PER_LINE]) + ",")
    return "\n".join(lines)


def lookup(rs, rust_fn, go_fn, doc, major):
    """A switch from a property's names to its table, from a Rust match of the same."""
    body = find(r"pub\(super\) fn " + rust_fn + r"\(name: &str\) -> Option<&'static Table> \{\s*match name \{(.*?)\n\s*_ => None,",
                rs, rust_fn)
    out = [f"// {doc}", f"func {go_fn}(name string) *Table {{", "\tswitch name {"]
    for names, target in re.findall(r"((?:\"[^\"]*\"\s*\|?\s*)+)=> Some\(&(\w+)\)", body):
        quoted = ", ".join('"%s"' % n for n in re.findall(r'"([^"]*)"', names))
        out.append(f"\tcase {quoted}:")
        out.append(f"\t\treturn &{go_name(target, major)}")
    out += ["\t}", "\treturn nil", "}"]
    return "\n".join(out)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv
    rs = open(args[0], encoding="utf-8").read()
    version = find(r'pub\(crate\) const VERSION: &str = "([^"]+)";', rs, "VERSION")
    major = version.split(".")[0]
    output = args[1] if len(args) > 1 else f"internal/ucd/tables{major}_gen.go"
    source = os.path.basename(args[0])

    parts = [
        f"// Code generated by tools/unicode/gen_tables.py from {source} of the corvus-regex-ecma262 Rust crate,",
        f"// which holds the Unicode {version} property tables of every engine. DO NOT EDIT.",
        "",
        "package ucd",
        "",
        f"// data{major} is the Unicode {version} data: its lookups by name and its case mappings.",
        f"var data{major} = data{{",
        f'\tversion:               "{version}",',
        f"\tcategoryTable:         categoryTable{major},",
        f"\tbinaryTable:           binaryTable{major},",
        f"\tscriptTable:           scriptTable{major},",
        f"\tscriptExtensionsTable: scriptExtensionsTable{major},",
        f"\tscriptNames:           scriptNames{major},",
        f"\tbinaryNames:           binaryNames{major},",
        f"\tcaseFolds:             caseFolds{major},",
        f"\tupperCases:            upperCases{major},",
        "}",
        "",
        lookup(rs, "category_table", f"categoryTable{major}",
               f"categoryTable{major} is the table of a General_Category value, by any of its names.", major),
        "",
        lookup(rs, "binary_table", f"binaryTable{major}",
               f"binaryTable{major} is the table of a binary property, by any of its names.", major),
        "",
        lookup(rs, "script_table", f"scriptTable{major}",
               f"scriptTable{major} is the table of a Script value, by any of its names.", major),
        "",
        lookup(rs, "script_extensions_table", f"scriptExtensionsTable{major}",
               f"scriptExtensionsTable{major} is the table of a Script_Extensions value, by any of its names.", major),
        "",
    ]

    names = find(r"pub\(super\) static SCRIPT_NAMES: &\[&\[&str\]\] = &\[(.*?)\n\];", rs, "SCRIPT_NAMES")
    parts.append(f"// scriptNames{major} are the names of each script, its long name first.")
    parts.append(f"var scriptNames{major} = [][]string{{")
    for row in re.findall(r"&\[([^\]]*)\]", names):
        parts.append("\t{" + ", ".join('"%s"' % n for n in re.findall(r'"([^"]*)"', row)) + "},")
    parts += ["}", ""]

    binary = find(r"pub\(super\) static BINARY_NAMES: &\[&str\] = &\[(.*?)\n\];", rs, "BINARY_NAMES")
    parts.append(f"// binaryNames{major} are the names of the binary properties.")
    parts.append(f"var binaryNames{major} = []string{{")
    for n in re.findall(r'"([^"]*)"', binary):
        parts.append(f'\t"{n}",')
    parts += ["}", ""]

    count = 0
    for m in re.finditer(r"pub\(super\) static (\w+): Table = Table \{(.*?)\n\};", rs, re.S):
        fields = dict(re.findall(r"(r16|r32): &\[(.*?)\]", m.group(2), re.S))
        r16, r32 = ints(fields.get("r16", "")), ints(fields.get("r32", ""))
        parts.append(f"var {go_name(m.group(1), major)} = Table{{")
        parts.append("\tr16: []uint16{" + ("\n" + numbers(r16, "\t\t") + "\n\t" if r16 else "") + "},")
        parts.append("\tr32: []uint32{" + ("\n" + numbers(r32, "\t\t") + "\n\t" if r32 else "") + "},")
        parts += ["}", ""]
        count += 1

    for rust, go, doc in (("CASE_FOLDS", f"caseFolds{major}", "map each code point to its simple case folding."),
                          ("UPPER_CASES", f"upperCases{major}", "map each code point to its simple uppercase.")):
        rows = find(r"pub\(super\) static " + rust + r": &\[CaseRange\] = &\[(.*?)\n\];", rs, rust)
        parts.append(f"// {go} {doc}")
        parts.append(f"var {go} = []CaseRange{{")
        for first, delta, length, mask in re.findall(
                r"CaseRange \{ first: (-?\w+), delta: (-?\w+), length: (\w+), mask: (\w+) \}", rows):
            parts.append(f"\t{{first: {first}, delta: {delta}, length: {length}, mask: {mask}}},")
        parts += ["}", ""]

    text = "\n".join(parts).rstrip("\n") + "\n"
    if check:
        current = open(output, encoding="utf-8").read() if os.path.exists(output) else ""
        if current != text:
            print(f"{output} is not what {args[0]} generates; run tools/unicode/gen_tables.py", file=sys.stderr)
            sys.exit(1)
        print(f"{output} is current ({count} tables)")
        return
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {output}: {count} tables, Unicode {version}")


if __name__ == "__main__":
    main()
