#!/usr/bin/env python3
"""Writes es2020_gen.go, the Unicode property names and values of the tables of ECMAScript 2020, from es2020.rs of the
corvus-regex-ecma262 Rust crate, so every engine's 2020 grammar knows the same names.

    python3 tools/unicode/gen_es2020.py <path to es2020.rs> [output] [--check]

With --check, the output is compared with the file in place and nothing is written: the exit status is 1 when they
differ.
"""
import os
import re
import sys

OUT = "es2020_gen.go"


def names(rs, rust_fn):
    """The names a Rust `matches!` of the function lists."""
    m = re.search(r"fn " + rust_fn + r"\(name: &str\) -> bool \{\s*matches!\(\s*name,(.*?)\)\s*\}", rs, re.S)
    if m is None:
        raise SystemExit(f"es2020.rs has no {rust_fn}: the generator needs updating for the crate's file")
    found = re.findall(r'"([^"]*)"', m.group(1))
    if not found:
        raise SystemExit(f"es2020.rs lists no names in {rust_fn}")
    return found


def switch(go_fn, doc, values):
    out = [f"// {go_fn} reports whether the name is one of {doc}.", f"func {go_fn}(name string) bool {{", "\tswitch name {"]
    out.append("\tcase " + ",\n\t\t".join(f'"{v}"' for v in values) + ":")
    out += ["\t\treturn true", "\t}", "\treturn false", "}"]
    return "\n".join(out)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv
    rs = open(args[0], encoding="utf-8").read()
    output = args[1] if len(args) > 1 else OUT
    tables = {fn: names(rs, fn) for fn in ("non_binary", "binary", "category", "script")}
    parts = [
        "// Code generated by tools/unicode/gen_es2020.py from es2020.rs of the corvus-regex-ecma262 Rust crate. DO NOT EDIT.",
        "",
        "package ecmaregex",
        "",
        "// The Unicode property names and values of the tables of ECMAScript 2020 (ECMA-262, 11th edition), the only ones",
        "// its grammar knows whatever the version of Unicode: tc39/ecma262 at the tag es2020, every name and alias of each.",
        "",
        "import \"strings\"",
        "",
        "// es2020HasProperty reports whether the expression between the braces of \\p{...} names a property, and a value of",
        "// it, of the tables: a name and a value joined by =, or the lone name of a General_Category value or of a binary",
        "// property.",
        "func es2020HasProperty(expr string) bool {",
        "\tname, value, ok := strings.Cut(expr, \"=\")",
        "\tswitch {",
        "\tcase !ok:",
        "\t\treturn es2020Category(expr) || es2020Binary(expr)",
        "\tcase name == \"General_Category\" || name == \"gc\":",
        "\t\treturn es2020Category(value)",
        "\t}",
        "\treturn es2020NonBinary(name) && es2020Script(value)",
        "}",
        "",
        switch("es2020NonBinary", "the non-binary properties", tables["non_binary"]),
        "",
        switch("es2020Binary", "the binary properties", tables["binary"]),
        "",
        switch("es2020Category", "the General_Category values", tables["category"]),
        "",
        switch("es2020Script", "the Script values", tables["script"]),
    ]
    text = "\n".join(parts) + "\n"
    count = sum(len(v) for v in tables.values())
    if check:
        current = open(output, encoding="utf-8").read() if os.path.exists(output) else ""
        if current != text:
            print(f"{output} is not what {args[0]} generates; run tools/unicode/gen_es2020.py", file=sys.stderr)
            sys.exit(1)
        print(f"{output} is current ({count} names)")
        return
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {output}: {count} names")


if __name__ == "__main__":
    main()
