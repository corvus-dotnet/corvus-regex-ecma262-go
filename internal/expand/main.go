// Command expand writes out the templates of the matcher, one file for each encoding, as go generate runs it from
// the module's root:
//
//	go run ./internal/expand [-check]
//
// A template is a file ending in _template.go with the build constraint ignore. In it unit_T is the unit of the text,
// isUTF8_T says whether the text is UTF-8, and any other name ending in _T is the name of that encoding, which ends in
// 8 or in 16. So vm_template.go becomes vm8_gen.go, with unit_T as byte, isUTF8_T as true and decode_T as decode8, and
// vm16_gen.go, with uint16, false and decode16. With -check nothing is written, and the exit status is 1 when a file
// written out would differ from the one in place.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

type encoding struct {
	suffix, unit, utf8 string
}

var encodings = []encoding{{"8", "byte", "true"}, {"16", "uint16", "false"}}

var name = regexp.MustCompile(`\b([A-Za-z][A-Za-z0-9]*)_T\b`)

func expand(template string, e encoding) []byte {
	// The build constraint and the doc comment of the template are its own.
	body := template[strings.Index(template, "package "):]
	body = strings.ReplaceAll(body, "unit_T", e.unit)
	body = strings.ReplaceAll(body, "isUTF8_T", e.utf8)
	body = name.ReplaceAllString(body, "${1}"+e.suffix)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/expand from the template; DO NOT EDIT.\n\n")
	b.WriteString(body)
	out, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "expand:", err)
		os.Exit(2)
	}
	return out
}

func main() {
	check := flag.Bool("check", false, "compare with the files in place and write nothing")
	flag.Parse()
	templates, _ := filepath.Glob("*_template.go")
	stale := false
	for _, t := range templates {
		src, err := os.ReadFile(t)
		if err != nil {
			fmt.Fprintln(os.Stderr, "expand:", err)
			os.Exit(2)
		}
		base := strings.TrimSuffix(t, "_template.go")
		for _, e := range encodings {
			out := expand(string(src), e)
			path := base + e.suffix + "_gen.go"
			if *check {
				if current, err := os.ReadFile(path); err != nil || !bytes.Equal(current, out) {
					fmt.Fprintf(os.Stderr, "%s is not what %s expands to; run go generate\n", path, t)
					stale = true
				}
				continue
			}
			if err := os.WriteFile(path, out, 0o644); err != nil {
				fmt.Fprintln(os.Stderr, "expand:", err)
				os.Exit(2)
			}
			fmt.Println("wrote", path)
		}
	}
	if stale {
		os.Exit(1)
	}
}
